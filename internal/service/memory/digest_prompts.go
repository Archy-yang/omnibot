package memory

// 沉淀管线 prompt(12-记忆系统技术方案 §7.2/§7.3)。
// 独立成文件便于审阅与后续调优;提取原则:宁可漏记,不可错记(PRD 红线)。

// pipelineSystemPrompt 沉淀管线唯一一次 LLM 调用:纪要 + 记忆提取一次产出
// (§7 修订:合并调用,LLM 成本减半,且两个产物基于同一次理解,语义一致)。
// summary 为"状态快照"式(M5.4):对话结束后现在哪些事是确定的,而非对话过程复述
// (实测流水账式纪要把关键结论埋在"用户说/助手答"的叙事里,检索命中率差)。
const pipelineSystemPrompt = `你是对话沉淀助手。请对用户给你的这段对话原文完成两件事，输出一个 JSON：

1. summary：把这段对话沉淀成一份"状态快照"——对话结束后，现在哪些事情是确定的、发生了什么变化。按以下三块组织，每块内一条一行（以 - 开头），没有内容的块整块省略：
   - 【关键决定与事实】已确定的安排、重要数字（金额/日期/数量/规格）、达成的结论，保留具体数字；
   - 【用户偏好】对话中体现的稳定偏好与倾向；
   - 【未决事项】悬而未决、待办、待确认的。
   严格要求：
   - 禁止复述对话过程："用户说/助手回答/用户问/然后/接着"这类叙事一律不写，只写状态与结论本身；
   - 闲聊、寒暄、与主题无关的过程性信息一律不收录；
   - 忠于原文，不编造、不添加原文没有的信息；第三人称、简体中文、全文 300 字以内。

   示例（仅示意格式）：
   【关键决定与事实】
   - 国庆西双版纳 9 人家庭游（9/27-10/4），机票与 4 室别墅已订
   - 8 天 7 晚行程已排定；租车测算约 350 元/天，高于打车方案
   【用户偏好】
   - 注重性价比，出行倾向打车而非包车
   【未决事项】
   - 交通方式未最终确定；实时票价待临行前核实

2. memories：提取值得长期记住的稳定信息（用户身份、偏好、习惯、长期项目背景、重要决定）。严格要求：
   - 只提取确定、稳定、长期有效的信息；一次性讨论、临时情绪、寒暄一律不提取；
   - 宁可漏记，不可错记；没有值得提取的就返回空数组 []；
   - 每条记忆是一句独立、自包含的陈述（如"用户是后端工程师"），50 字以内；
   - source_message_ids 填该信息依据的全部消息编号数组（原文中 [消息#N|...] 的 N，
     可多条——信息往往由多轮交叉得出；无法确定填空数组 []。

只输出 JSON，不要任何其他文字（summary 内的换行用 \n 表示），格式如下：
{"summary":"...","memories":[{"content":"...","source_message_ids":[0]}]}`
