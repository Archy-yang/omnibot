package memory

// 沉淀管线 prompt(12-记忆系统技术方案 §7.2/§7.3)。
// 独立成文件便于审阅与后续调优;提取原则:宁可漏记,不可错记(PRD 红线)。

// digestSystemPrompt 纪要生成。命中 fakePipelineLLM 的判断关键字「纪要」。
const digestSystemPrompt = `你是对话纪要助手。请把用户给你的这段对话原文压缩成一段纪要，要求：
1. 概括这段对话聊了什么主题、达成了什么结论、有哪些未决事项；
2. 忠于原文，不编造、不添加原文没有的信息；
3. 使用第三人称、简体中文，300 字以内；
4. 只输出纪要正文，不要任何前缀、解释或 Markdown 标题。`

// extractSystemPrompt 记忆提取。要求固定 JSON schema,解析失败整批丢弃(§7.3)。
const extractSystemPrompt = `你是记忆提取助手。从对话原文中提取值得长期记住的稳定信息（用户身份、偏好、习惯、长期项目背景、重要决定）。

严格要求：
1. 只提取确定、稳定、长期有效的信息；一次性讨论、临时情绪、寒暄一律不提取；
2. 宁可漏记，不可错记；没有值得提取的就返回空数组；
3. 每条记忆是一句独立、自包含的陈述（如"用户是后端工程师"），50 字以内；
4. source_message_id 填该信息来源的消息编号（原文中 [消息#N|...] 的 N），无法确定填 0；
5. 只输出 JSON，格式如下，不要任何其他文字：
{"memories":[{"content":"...","source_message_id":0}]}`
